'use strict';
// Writes public/howto/index.js from the screenshots in public/howto/<gameId>/<cardIndex>.jpg, so the how-to cards know which
// real-footage pictures exist. Run after adding or replacing screenshots (scripts/howto-shot.js):  node scripts/howto-index.js
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..', 'public', 'howto');
const images = {};
for (const game of fs.readdirSync(ROOT, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name).sort()) {
  const cards = fs.readdirSync(path.join(ROOT, game))
    .map((f) => /^(\d+)\.jpg$/.exec(f)).filter(Boolean).map((m) => Number(m[1])).sort((a, b) => a - b);
  if (cards.length) images[game] = cards;
}
const out = `// Generated by scripts/howto-index.js from public/howto/<game>/<card>.jpg: the real-footage pictures for the how-to cards.\n`
  + `window.CardTable = window.CardTable || {};\nwindow.CardTable.howtoImages = ${JSON.stringify(images)};\n`;
fs.writeFileSync(path.join(ROOT, 'index.js'), out);
console.log(`howto index: ${Object.keys(images).length} games, ${Object.values(images).reduce((n, a) => n + a.length, 0)} pictures`);
